"""Mock CRM API: the external system the agents depend on.

Run it:
    uvicorn mock_crm.server:app --port 8077
Endpoints:
    GET /health
    GET /clients/{client_id}
    GET /clients/{client_id}/transactions?limit=200
    GET /clients/{client_id}/notes
Data comes from data/clients/*.json (generated by scripts/generate_clients.py).
"""
from __future__ import annotations

import json
import os


from fastapi import FastAPI, Header, HTTPException, Request
from fastapi.responses import JSONResponse

from mock_crm import chaos

DATA_DIR = os.getenv("DATA_DIR", "data")
app = FastAPI(title="Mock CRM", version="0.1.0")


def _load(client_id: str) -> dict:
    path = os.path.join(DATA_DIR, "clients", f"{client_id}.json")
    if not os.path.exists(path):
        raise HTTPException(status_code=404, detail=f"unknown client: {client_id}")
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


@app.middleware("http")
async def chaos_middleware(request: Request, call_next):
    """Injected failures happen before the handler, except for /health."""
    if request.url.path.startswith("/health"):
        return await call_next(request)
    mode = request.headers.get("x-chaos") or chaos.pick_mode()
    if mode == "timeout":
        chaos.apply_failure("timeout")
        return JSONResponse(status_code=504, content={"detail": "mock timeout"})
    if mode == "http_500":
        return JSONResponse(status_code=500, content={"detail": "mock internal error"})
    request.state.chaos_mode = mode
    return await call_next(request)


@app.get("/health")
def health() -> dict:
    return {"status": "ok", "chaos_rate": chaos.chaos_rate()}


@app.get("/clients/{client_id}")
def get_client(client_id: str, request: Request) -> dict:
    data = _load(client_id)
    profile = {k: v for k, v in data.items() if k not in ("transactions", "advisor_notes")}
    if getattr(request.state, "chaos_mode", None) == "missing_field":
        profile.pop("risk_profile", None)          # R: missing field must degrade, not crash
    return profile


@app.get("/clients/{client_id}/transactions")
def get_transactions(client_id: str, limit: int = 200) -> dict:
    data = _load(client_id)
    rows = sorted(data.get("transactions", []), key=lambda t: t["date"], reverse=True)
    return {"client_id": client_id, "transactions": rows[:limit]}


@app.get("/clients/{client_id}/notes")
def get_notes(client_id: str) -> dict:
    data = _load(client_id)
    return {"client_id": client_id, "notes": data.get("advisor_notes", [])}
